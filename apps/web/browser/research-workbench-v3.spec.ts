test("Research header exposes New directly with a tooltip and protects the current draft", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto("/research?new");
  await page.getByRole("button", { name: "Factor Evaluation", exact: true }).click();
  const header = page.locator(".research-page-header");
  const newResearch = header.getByRole("button", { name: "New research", exact: true });
  await expect(newResearch).toBeVisible();
  await expect(header.getByRole("button", { name: "More research actions", exact: true })).toHaveCount(0);
  await newResearch.hover();
  const tooltip = page.locator('[data-slot="tooltip-content"]');
  await expect(tooltip).toBeVisible();
  await expect(tooltip).toHaveText("New research");
  await newResearch.press("Escape");
  await expect(tooltip).toHaveCount(0);

  const formula = page.getByRole("textbox", { name: "Alpha formula", exact: true });
  await formula.fill("close");
  await newResearch.focus();
  await expect(tooltip).toBeVisible();
  await newResearch.press("Enter");
  const confirmation = page.getByRole("alertdialog", { name: "New research", exact: true });
  await expect(confirmation).toBeVisible();
  await confirmation.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(confirmation).toHaveCount(0);
  await expect(formula).toHaveText("close");
  await expect(newResearch).toBeFocused();

  const researchName = header.getByRole("button", { name: "Untitled research", exact: true });
  await expect(researchName).toHaveCSS("font-size", "16px");
  await expect(researchName).toHaveCSS("line-height", "24px");
  await expect(header.getByRole("heading", { name: "Untitled research", exact: true })).toHaveCount(0);
  const identity = (await researchName.boundingBox())!;
  const folder = (await header.getByRole("button", { name: "Research Folders", exact: true }).boundingBox())!;
  await expect(header.getByRole("status")).toHaveCount(0);
  expect(folder.x).toBeGreaterThan(identity.x + identity.width);
  expect(Math.abs(folder.y + folder.height / 2 - identity.y - identity.height / 2)).toBeLessThan(1);
  await page.screenshot({ path: testInfo.outputPath("research-header.png") });

  await newResearch.click();
  await confirmation.getByRole("button", { name: "New research", exact: true }).click();
  await expect(confirmation).toHaveCount(0);
  await expect(page.getByRole("heading", { name: "Choose a research type" })).toBeVisible();
  await page.getByRole("button", { name: "Factor Evaluation", exact: true }).click();
  await expect(formula.locator(".cm-placeholder")).toHaveText("rank(pct_change(close, 20))");
});

test("Research actions stay at the viewport bottom while scrolling and follow the sidebar", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto("/research?new");
  await page.getByRole("button", { name: "Factor Evaluation", exact: true }).click();
  const actions = page.getByRole("group", { name: "Research actions", exact: true });
  const check = actions.getByRole("button", { name: "Check configuration", exact: true });
  await expect(check).toBeVisible();
  await expect(actions.getByRole("button", { name: "Run evaluation", exact: true })).toBeVisible();
  await expect(page.locator(".research-page-header").getByRole("button", { name: /Check configuration|Run evaluation|Run backtest/ })).toHaveCount(0);
  const firstBox = (await actions.boundingBox())!;
  expect(900 - firstBox.y - firstBox.height).toBe(16);

  const expectCentered = async () => {
    await expect.poll(async () => {
      const bar = (await actions.boundingBox())!;
      const main = (await page.locator(".application-frame").boundingBox())!;
      return Math.abs(bar.x + bar.width / 2 - main.x - main.width / 2);
    }).toBeLessThan(1);
  };
  await expectCentered();
  await page.getByRole("button", { name: "Back to research types", exact: true }).click();
  await page.getByRole("button", { name: "Strategy Backtest", exact: true }).click();
  await expect(actions.getByRole("button", { name: "Run backtest", exact: true })).toBeVisible();
  // Use the full source editor so this desktop page actually requires scrolling.
  await page.getByRole("radio", { name: "Python authoring", exact: true }).check();
  const notes = page.getByRole("textbox", { name: "Research notes (optional)", exact: true });
  await notes.fill("Research notes remain reachable above the action bar.");
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight));
  await expect(page.locator(".research-page-header")).not.toBeInViewport();
  await expect(actions).toBeInViewport({ ratio: 1 });
  const scrolledBox = (await actions.boundingBox())!;
  expect(scrolledBox.y).toBe(firstBox.y);
  const notesBox = (await notes.boundingBox())!;
  expect(notesBox.y + notesBox.height).toBeLessThan(scrolledBox.y - 8);
  await notes.press("Tab");
  await expect(page.getByRole("textbox", { name: "Research start date", exact: true })).toBeFocused();
  await check.focus();
  await expect(check).toBeFocused();

  await page.getByRole("separator", { name: "Resize sidebar", exact: true }).press("End");
  await expectCentered();
  await page.getByRole("button", { name: "Collapse sidebar", exact: true }).click();
  await expect(page.locator(".app-shell")).toHaveClass(/app-shell-collapsed/);
  await expectCentered();
  await expect(actions).toBeInViewport({ ratio: 1 });
  await page.screenshot({ path: testInfo.outputPath("floating-research-actions.png") });
});

test("Research modes keep one focused editor and expose help by hover and keyboard", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goto("/research?new");
  await page.getByRole("button", { name: "Factor Evaluation", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Alpha formula", exact: true })).toBeVisible();
  await expect(page.locator(".research-page-header").getByRole("button", { name: "Untitled research", exact: true })).toHaveCSS("font-size", "16px");

  await page.getByRole("button", { name: "Back to research types", exact: true }).click();
  await page.getByRole("button", { name: "Strategy Backtest", exact: true }).click();
  const modes = page.getByRole("radiogroup", { name: "Strategy authoring", exact: true });
  const modularMode = modes.getByRole("radio", { name: "Modular authoring", exact: true });
  const pythonMode = modes.getByRole("radio", { name: "Python authoring", exact: true });
  await expect(modularMode).toHaveCSS("opacity", "1");
  await expect(modularMode).toHaveCSS("width", "16px");
  await modularMode.focus();
  await modularMode.press("ArrowRight");
  await expect(pythonMode).toBeChecked();
  await expect(modularMode).not.toBeChecked();
  await pythonMode.press("ArrowLeft");
  await expect(modularMode).toBeChecked();
  await expect(pythonMode).not.toBeChecked();
  for (const mode of ["Modular authoring", "Python authoring"]) {
    const modeHelp = page.getByRole("button", { name: `About ${mode}`, exact: true });
    await expect(modeHelp.locator("svg")).toHaveCSS("width", "12px");
    await modeHelp.hover();
    await expect(page.getByRole("dialog", { name: mode, exact: true })).toBeVisible();
    await expect(page.getByRole("radio", { name: "Modular authoring", exact: true })).toBeChecked();
    await modeHelp.press("Escape");
  }
  const tabs = page.getByRole("tablist", { name: "Strategy modules" });
  await expect(tabs.getByRole("tab")).toHaveCount(4);
  const portfolio = tabs.getByRole("tab", { name: /Portfolio/ });
  await expect(tabs.getByRole("tab", { name: "Universe", exact: true })).toHaveAttribute("aria-selected", "true");
  await portfolio.click();
  await expect(portfolio).toHaveAttribute("aria-selected", "true");
  await expect(page.getByLabel("Holdings count", { exact: true })).toBeVisible();
  await expect(page.getByRole("textbox", { name: "Alpha formula", exact: true })).not.toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("rules.png") });

  const help = page.getByRole("button", { name: "About Total stock exposure (%)" });
  await help.hover();
  const info = page.getByRole("dialog", { name: "Total stock exposure (%)" });
  await expect(info).toContainText("remaining capital stays in cash");
  await help.click();
  await expect(info).toBeVisible();
  await help.press("Escape");
  await expect(info).toHaveCount(0);
  await expect(help).toBeFocused();
  await help.press("Enter");
  await expect(info).toBeVisible();
  await help.press("Escape");
  await expect(info).toHaveCount(0);

  await portfolio.focus();
  await portfolio.press("ArrowRight");
  await expect(tabs.getByRole("tab", { name: /Risk/ })).toHaveAttribute("aria-selected", "true");
  await expect(page.getByRole("switch", { name: "Stop loss", exact: true })).toBeVisible();
  await expect(page.getByRole("textbox", { name: "Stop loss (%)", exact: true })).not.toBeVisible();
  await expect(page.getByLabel("Holdings count", { exact: true })).not.toBeVisible();

  const rulesEditorBox = (await page.locator(".research-editor-column").boundingBox())!;
  await page.getByRole("radio", { name: "Python authoring", exact: true }).check();
  await expect(page.getByRole("textbox", { name: "Python source", exact: true })).toBeVisible();
  await expect(page.getByText("Python source", { exact: true }).filter({ visible: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Expand editor", exact: true })).toHaveCount(0);
  await expect(page.getByText("System input", { exact: true })).toHaveCount(0);
  const pythonHelp = page.getByRole("button", { name: "Python reference", exact: true });
  const sourceLabel = page.getByText("Python source", { exact: true }).filter({ visible: true });
  const sourceLabelBox = (await sourceLabel.boundingBox())!;
  const helpButtonBox = (await pythonHelp.boundingBox())!;
  const helpIconBox = (await pythonHelp.locator("svg").boundingBox())!;
  expect(helpIconBox.x - sourceLabelBox.x - sourceLabelBox.width).toBeGreaterThanOrEqual(0);
  expect(helpIconBox.x - sourceLabelBox.x - sourceLabelBox.width).toBeLessThanOrEqual(4);
  expect(helpButtonBox.x - sourceLabelBox.x - sourceLabelBox.width).toBeGreaterThanOrEqual(0);
  expect(helpButtonBox.x - sourceLabelBox.x - sourceLabelBox.width).toBeLessThanOrEqual(4);
  expect(helpButtonBox.width).toBe(28);
  const editorFrame = page.locator(".research-editor-column .cm-editor").filter({ visible: true }).locator("..");
  const editorFrameBox = (await editorFrame.boundingBox())!;
  expect(editorFrameBox.width).toBeGreaterThan(rulesEditorBox.width);
  expect(editorFrameBox.height).toBeGreaterThanOrEqual(600);
  const modeRadioBox = (await modularMode.boundingBox())!;
  expect(Math.abs(sourceLabelBox.x - editorFrameBox.x)).toBeLessThan(1);
  const browseFieldsBox = (await page.getByRole("button", { name: "Browse fields", exact: true }).boundingBox())!;
  expect(browseFieldsBox.x).toBeGreaterThan(helpButtonBox.x + helpButtonBox.width);
  expect(Math.abs(browseFieldsBox.x + browseFieldsBox.width - editorFrameBox.x - editorFrameBox.width)).toBeLessThan(1);
  expect(Math.abs(modeRadioBox.x - editorFrameBox.x)).toBeLessThan(1);
  await pythonHelp.press("Enter");
  const pythonInfo = page.getByRole("dialog", { name: "Python reference", exact: true });
  await expect(pythonInfo).toContainText("System input");
  await expect(pythonInfo).toContainText("Strategy output");
  await expect(pythonInfo).toContainText("System execution");
  await expect(pythonInfo).toContainText("compute(data, state)");
  await expect(pythonInfo).toContainText("Targets(weights, update=flags)");
  const pythonInfoBox = (await pythonInfo.boundingBox())!;
  expect(pythonInfoBox.y).toBeGreaterThanOrEqual(0);
  expect(pythonInfoBox.y + pythonInfoBox.height).toBeLessThanOrEqual(960);
  await pythonHelp.press("Escape");
  await expect(page.getByRole("textbox", { name: "Python source", exact: true })).toBeVisible();
  await expect(tabs).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Run backtest", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("python.png") });

  await page.getByRole("button", { name: "Back to research types", exact: true }).click();
  await page.getByRole("button", { name: "Factor Evaluation", exact: true }).click();
  await expect(page.getByRole("textbox", { name: "Alpha formula", exact: true })).toBeVisible();
  await expect(page.getByRole("button", { name: "Run evaluation", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("factor.png") });
});


import { expect, test } from "./workbench-fixture";

test("Strategy navigation keeps the base universe before an optional Python filter and preserves both drafts", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1528, height: 954 });
  await page.addInitScript(() => localStorage.setItem("quantgrove.interface-language", "zh-CN"));
  await page.goto("/research?new");
  await page.getByRole("button", { name: "策略回测", exact: true }).click();
  await expect(page.getByRole("radiogroup", { name: "策略编写方式", exact: true })).toBeVisible();
  await expect(page.getByText("策略摘要", { exact: true })).toHaveCount(0);
  const tabs = page.getByRole("tablist", { name: "策略模块", exact: true });
  await expect(tabs.getByRole("tab")).toHaveText(["股票池", "选股信号", "组合构建", "风险管理"]);
  expect((await tabs.boundingBox())!.height).toBeLessThanOrEqual(48);
  await tabs.getByRole("tab", { name: "股票池", exact: true }).click();
  const panel = page.getByRole("tabpanel", { name: /^股票池/ });
  expect((await panel.boundingBox())!.height).toBeLessThan(220);
  await expect(panel.getByRole("heading", { name: "股票池", exact: true })).toHaveCount(0);
  const modes = panel.getByRole("radiogroup", { name: "股票池编写方式", exact: true });
  await expect(modes.getByRole("radio")).toHaveCount(2);
  const universe = panel.getByRole("combobox", { name: "基础股票范围", exact: true });
  await universe.click();
  await page.getByRole("option", { name: "流动性前 300 只", exact: true }).click();
  const configure = modes.getByRole("radio", { name: "配置", exact: true });
  const filter = modes.getByRole("radio", { name: "Code", exact: true });
  await expect(configure).toBeChecked();
  await expect(configure).toBeVisible();
  await expect(filter).toBeVisible();
  await expect(filter).not.toBeChecked();
  expect((await filter.boundingBox())!.y).toBeGreaterThan((await universe.boundingBox())!.y);
  const help = panel.getByRole("button", { name: "股票池编写方式说明", exact: true });
  await help.hover();
  await expect(page.getByRole("dialog", { name: "股票池编写方式", exact: true })).toContainText("基础范围");
  await help.press("Escape");
  await panel.getByText("Code", { exact: true }).click();
  await expect(filter).toBeChecked();
  await filter.press("ArrowLeft");
  await expect(filter).not.toBeChecked();
  await configure.press("ArrowRight");
  const editor = panel.getByRole("textbox", { name: "Python 源码", exact: true });
  await expect(editor).toBeVisible();
  await expect(panel.getByRole("button", { name: "展开编辑器", exact: true })).toHaveCount(0);
  const sourceLabel = panel.getByText("Python 源码", { exact: true });
  const browseFields = panel.getByRole("button", { name: "浏览字段", exact: true });
  await expect(sourceLabel).toBeVisible();
  await expect(browseFields).toBeVisible();
  const editorBox = (await editor.boundingBox())!;
  expect((await sourceLabel.boundingBox())!.y).toBeLessThan(editorBox.y);
  expect((await browseFields.boundingBox())!.y).toBeLessThan(editorBox.y);
  await editor.fill("# candidate selection draft");
  const editorFrame = panel.locator(".cm-editor").locator("..");
  await editorFrame.scrollIntoViewIfNeeded();
  const initialFrame = (await editorFrame.boundingBox())!;
  const notes = page.getByRole("textbox", { name: "研究备注（可选）", exact: true });
  const notesBox = (await notes.boundingBox())!;
  const conditionsBox = (await page.getByRole("complementary", { name: "运行设置", exact: true }).boundingBox())!;
  expect(notesBox.y - initialFrame.y - initialFrame.height).toBeLessThan(100);
  expect(notesBox.x + notesBox.width).toBeLessThan(conditionsBox.x);
  await page.mouse.move(initialFrame.x + initialFrame.width - 4, initialFrame.y + initialFrame.height - 4);
  await page.mouse.down();
  await page.mouse.move(initialFrame.x + initialFrame.width - 4, initialFrame.y + initialFrame.height - 164, { steps: 10 });
  await page.mouse.up();
  await expect.poll(async () => (await editorFrame.boundingBox())!.height).toBeLessThan(initialFrame.height);
  await expect(editor).toHaveText("# candidate selection draft");
  const resizedHeight = (await editorFrame.boundingBox())!.height;
  const universeTab = tabs.getByRole("tab", { name: /股票池/ });
  await expect(universeTab.getByText("Python", { exact: true })).toHaveCount(0);
  await tabs.getByRole("tab", { name: "选股信号", exact: true }).click();
  await expect(universeTab.getByText("Python", { exact: true })).toHaveCount(0);
  await tabs.getByRole("tab", { name: /股票池/ }).click();
  await expect(universeTab.getByText("Python", { exact: true })).toHaveCount(0);
  await expect(editor).toHaveText("# candidate selection draft");
  expect((await editorFrame.boundingBox())!.height).toBe(resizedHeight);
  await configure.check();
  await expect(filter).not.toBeChecked();
  await expect(editor).not.toBeVisible();
  await expect(universe).toContainText("流动性前 300 只");
  await tabs.getByRole("tab", { name: "股票池", exact: true }).press("End");
  await expect(tabs.getByRole("tab", { name: "风险管理", exact: true })).toHaveAttribute("aria-selected", "true");
  await tabs.getByRole("tab", { name: "风险管理", exact: true }).press("Home");
  await expect(tabs.getByRole("tab", { name: "股票池", exact: true })).toHaveAttribute("aria-selected", "true");
  await page.screenshot({ path: testInfo.outputPath("strategy-tabs.png") });
  await filter.check();
  await expect(editor).toHaveText("# candidate selection draft");
  for (const name of ["选股信号", "组合构建", "风险管理"]) {
    await tabs.getByRole("tab", { name, exact: true }).click();
    const stage = page.getByRole("tabpanel", { name, exact: true });
    const choices = stage.getByRole("radiogroup");
    await expect(choices.getByRole("radio")).toHaveCount(2);
    const configured = choices.getByRole("radio", { name: "配置", exact: true });
    const coded = choices.getByRole("radio", { name: "Code", exact: true });
    await expect(configured).toBeChecked();
    await configured.press("ArrowRight");
    await expect(coded).toBeChecked();
    const source = stage.getByRole("textbox", { name: "Python 源码", exact: true });
    await source.fill(`# ${name} draft`);
    await coded.press("ArrowLeft");
    await expect(configured).toBeChecked();
    await expect(source).not.toBeVisible();
    await coded.check();
    await expect(source).toHaveText(`# ${name} draft`);
    await configured.check();
  }
  await tabs.getByRole("tab", { name: "股票池", exact: true }).click();
  await expect(filter).toBeChecked();
  await expect(editor).toHaveText("# candidate selection draft");
  await page.getByRole("radio", { name: "Python 编写", exact: true }).check();
  await expect(tabs).toHaveCount(0);
  await expect(page.getByText("策略摘要", { exact: true })).toHaveCount(0);
  await page.getByRole("radio", { name: "分模块编写", exact: true }).check();
  await tabs.getByRole("tab", { name: /股票池/ }).click();
  await expect(editor).toHaveText("# candidate selection draft");
});

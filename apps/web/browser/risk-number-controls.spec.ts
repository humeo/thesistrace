import { expect, test } from "./workbench-fixture";

test("Risk numeric controls step, retain decimals, validate and preserve their draft", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1626, height: 954 });
  await page.addInitScript(() => localStorage.setItem("quantgrove.interface-language", "zh-CN"));
  const submissions: Record<string, unknown>[] = [];
  await page.route("**/api/research-runs", route => {
    submissions.push(route.request().postDataJSON());
    return route.fulfill({ status: 503, json: { code: "RESEARCH_ADMISSION_UNAVAILABLE" } });
  });
  await page.goto("/research?new");
  await page.getByRole("button", { name: "策略回测", exact: true }).click();
  await page.getByLabel("研究开始日期", { exact: true }).fill("2026-08-04");
  await page.getByLabel("研究结束日期", { exact: true }).fill("2026-08-05");
  await page.getByRole("tab", { name: "股票池", exact: true }).click();
  await page.getByRole("combobox", { name: "基础股票范围", exact: true }).click();
  await page.getByRole("option", { name: "流动性前 300 只", exact: true }).click();
  await page.getByRole("tab", { name: "选股信号", exact: true }).click();
  await page.getByRole("textbox", { name: "Alpha 公式", exact: true }).fill("close");
  await page.getByRole("tab", { name: "风险管理", exact: true }).click();
  await page.getByRole("switch", { name: "累计止盈", exact: true }).check();
  const threshold = page.locator("#take-profit-0-profitThreshold");
  const reduction = page.locator("#take-profit-0-cumulativeReduction");
  await threshold.fill("10.5");
  await page.getByRole("button", { name: "增加盈利阈值（%）", exact: true }).click();
  await expect(threshold).toHaveValue("11.5");
  await threshold.press("ArrowDown");
  await expect(threshold).toHaveValue("10.5");
  await threshold.fill("0.01");
  await reduction.fill("100");
  await expect(page.getByRole("button", { name: "增加累计减仓（%）", exact: true })).toBeDisabled();
  await reduction.fill("101");
  await page.getByRole("button", { name: "检查配置", exact: true }).click();
  await expect(reduction).toBeFocused();
  await expect(reduction).toHaveValue("101");
  await expect(reduction).toHaveAttribute("aria-invalid", "true");
  await reduction.fill("30");
  await page.getByRole("button", { name: "添加止盈层级", exact: true }).click();
  const secondThreshold = page.locator("#take-profit-1-profitThreshold");
  await secondThreshold.fill("0.005");
  await page.locator("#take-profit-1-cumulativeReduction").fill("60");
  await page.getByRole("button", { name: "检查配置", exact: true }).click();
  await expect(secondThreshold).toBeFocused();
  await expect(secondThreshold).toHaveAttribute("aria-invalid", "true");
  await secondThreshold.fill("20");
  const stopLoss = page.getByLabel("止损（%）", { exact: true });
  const holding = page.getByLabel("最长持有（交易日）", { exact: true });
  await page.getByRole("switch", { name: "止损", exact: true }).check();
  await page.getByRole("switch", { name: "最长持有", exact: true }).check();
  await stopLoss.fill("10.25");
  await holding.fill("5");
  await holding.press("ArrowUp");
  await expect(holding).toHaveValue("6");
  await holding.fill("");
  await expect(holding).toHaveValue("");
  await page.getByRole("switch", { name: "最长持有", exact: true }).uncheck();
  await expect(holding).not.toBeVisible();
  await page.getByRole("switch", { name: "回撤限制", exact: true }).check();
  await page.getByLabel("回撤阈值（%）", { exact: true }).fill("10");
  await page.getByLabel("股票最大仓位（%）", { exact: true }).fill("30");
  await page.getByLabel("冷却期（交易日）", { exact: true }).fill("2");
  const drawdownBox = (await page.getByLabel("回撤阈值（%）", { exact: true }).boundingBox())!;
  const exposureBox = (await page.getByLabel("股票最大仓位（%）", { exact: true }).boundingBox())!;
  expect(Math.abs(drawdownBox.y - exposureBox.y)).toBeLessThan(1);
  await page.getByRole("button", { name: "回撤限制说明", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "回撤限制", exact: true })).toContainText("开启后须填写三个字段");
  await page.keyboard.press("Escape");
  const modes = page.getByRole("radiogroup", { name: "风险管理编写方式", exact: true });
  await modes.getByRole("radio", { name: "Code", exact: true }).check();
  await modes.getByRole("radio", { name: "配置", exact: true }).check();
  await expect(threshold).toHaveValue("0.01");
  await expect(secondThreshold).toHaveValue("20");
  await page.reload();
  await page.getByRole("tab", { name: "风险管理", exact: true }).click();
  await expect(threshold).toHaveValue("0.01");
  await expect(stopLoss).toHaveValue("10.25");
  await expect(page.getByRole("switch", { name: "最长持有", exact: true })).not.toBeChecked();
  await page.screenshot({ path: testInfo.outputPath("risk-number-controls.png"), fullPage: true });
  await page.getByRole("button", { name: "运行回测", exact: true }).click();
  await expect.poll(() => submissions.length).toBe(1);
  expect(submissions[0]).toMatchObject({ modules: { risk_management: {
    kind: "builtin_risk/v1", stop_loss_threshold: 0.1025,
    take_profit_tiers: [{ profit_threshold: 0.0001, cumulative_reduction: 0.3 }, { profit_threshold: 0.2, cumulative_reduction: 0.6 }],
    portfolio_drawdown: { drawdown_threshold: 0.1, maximum_stock_exposure: 0.3, cooldown_sessions: 2 },
  } } });
});

test("Risk switches exclude disabled parameters and preserve them across refresh", async ({ page }) => {
  await page.setViewportSize({ width: 1626, height: 954 });
  await page.addInitScript(() => localStorage.setItem("quantgrove.interface-language", "zh-CN"));
  const submissions: Record<string, unknown>[] = [];
  await page.route("**/api/research-runs", route => {
    submissions.push(route.request().postDataJSON());
    return route.fulfill({ status: 503, json: { code: "RESEARCH_ADMISSION_UNAVAILABLE" } });
  });
  await page.goto("/research?new");
  await page.getByRole("button", { name: "策略回测", exact: true }).click();
  await page.getByLabel("研究开始日期", { exact: true }).fill("2026-08-04");
  await page.getByLabel("研究结束日期", { exact: true }).fill("2026-08-05");
  await page.getByRole("tab", { name: "股票池", exact: true }).click();
  await page.getByRole("combobox", { name: "基础股票范围", exact: true }).click();
  await page.getByRole("option", { name: "流动性前 300 只", exact: true }).click();
  await page.getByRole("tab", { name: "选股信号", exact: true }).click();
  await page.getByRole("textbox", { name: "Alpha 公式", exact: true }).fill("close");
  await page.getByRole("tab", { name: "风险管理", exact: true }).click();
  const names = ["止损", "最长持有", "累计止盈", "回撤限制"];
  for (const name of names) await expect(page.getByRole("switch", { name, exact: true })).not.toBeChecked();
  await expect(page.getByLabel("止损（%）", { exact: true })).not.toBeVisible();
  await expect(page.getByRole("button", { name: "添加止盈层级", exact: true })).not.toBeVisible();
  await page.getByRole("switch", { name: "回撤限制", exact: true }).check();
  await page.getByRole("button", { name: "检查配置", exact: true }).click();
  await expect(page.getByLabel("回撤阈值（%）", { exact: true })).toBeFocused();
  await expect(page.getByLabel("回撤阈值（%）", { exact: true })).toHaveAttribute("aria-invalid", "true");
  await page.getByLabel("回撤阈值（%）", { exact: true }).fill("10");
  await page.getByLabel("股票最大仓位（%）", { exact: true }).fill("30");
  await page.getByLabel("冷却期（交易日）", { exact: true }).fill("5");
  await page.getByRole("switch", { name: "回撤限制", exact: true }).uncheck();
  await page.getByRole("switch", { name: "止损", exact: true }).check();
  await page.getByLabel("止损（%）", { exact: true }).fill("101");
  await page.getByRole("switch", { name: "止损", exact: true }).uncheck();
  await page.getByRole("switch", { name: "累计止盈", exact: true }).check();
  await expect(page.locator("#take-profit-0-profitThreshold")).toHaveValue("");
  await page.getByRole("switch", { name: "累计止盈", exact: true }).uncheck();
  await page.getByRole("button", { name: "运行回测", exact: true }).click();
  await expect.poll(() => submissions.length).toBe(1);
  expect(submissions[0]).toHaveProperty("modules.risk_management", "no_risk/v1");
  await page.reload();
  await page.getByRole("tab", { name: "风险管理", exact: true }).click();
  for (const name of names) await expect(page.getByRole("switch", { name, exact: true })).not.toBeChecked();
  await page.getByRole("switch", { name: "止损", exact: true }).check();
  await expect(page.getByLabel("止损（%）", { exact: true })).toHaveValue("101");
  await page.getByRole("button", { name: "运行回测", exact: true }).click();
  await expect(page.getByLabel("止损（%）", { exact: true })).toHaveAttribute("aria-invalid", "true");
  expect(submissions).toHaveLength(1);
  await page.getByLabel("止损（%）", { exact: true }).fill("10");
  await page.getByRole("switch", { name: "回撤限制", exact: true }).check();
  await expect(page.getByLabel("股票最大仓位（%）", { exact: true })).toHaveValue("30");
  await page.getByRole("radiogroup", { name: "风险管理编写方式", exact: true }).getByRole("radio", { name: "Code", exact: true }).check();
  await page.getByRole("radiogroup", { name: "风险管理编写方式", exact: true }).getByRole("radio", { name: "配置", exact: true }).check();
  await expect(page.getByRole("switch", { name: "止损", exact: true })).toBeChecked();
  await expect(page.getByRole("switch", { name: "回撤限制", exact: true })).toBeChecked();
  await page.getByRole("switch", { name: "累计止盈", exact: true }).check();
  await page.getByRole("button", { name: "移除第 1 层", exact: true }).click();
  await expect(page.getByRole("switch", { name: "累计止盈", exact: true })).not.toBeChecked();
  await page.getByRole("button", { name: "运行回测", exact: true }).click();
  await expect.poll(() => submissions.length).toBe(2);
  expect(submissions[1]).toHaveProperty("modules.risk_management", {
    kind: "builtin_risk/v1", stop_loss_threshold: 0.1,
    portfolio_drawdown: { drawdown_threshold: 0.1, maximum_stock_exposure: 0.3, cooldown_sessions: 5 },
  });
});

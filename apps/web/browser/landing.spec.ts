import { expect, test } from '@playwright/test';
import { createServer, type ViteDevServer } from 'vite';
import { fileURLToPath } from 'node:url';
import { createServer as createPortServer, type AddressInfo } from 'node:net';
let server: ViteDevServer;
let origin: string;
test.beforeAll(async () => {
  // Vite treats port 0 as its default port. Reserve an OS-selected port first.
  const reservation = createPortServer();
  await new Promise<void>(resolve => reservation.listen(0, '127.0.0.1', resolve));
  const port = (reservation.address() as AddressInfo).port;
  await new Promise<void>((resolve, reject) => reservation.close(error => error ? reject(error) : resolve()));
  server = await createServer({ root: fileURLToPath(new URL('..', import.meta.url)), server: { host: '127.0.0.1', port, strictPort: true }, logLevel: 'error' });
  await server.listen();
  origin = server.resolvedUrls!.local[0];
});
test.afterAll(async () => { await server?.close(); });
for (const width of [1220, 1440]) {
  test(`public landing language, evidence preview and login at ${width}px`, async ({ page }) => {
    // Includes cold Vite transforms, both language captures and the lazy auth route.
    test.setTimeout(60_000);
    const apiRequests: string[] = [];
    await page.route('**/api/**', async route => {
      apiRequests.push(route.request().url());
      await route.fulfill({ contentType: 'application/json', body: 'null' });
    });
    await page.setViewportSize({ width, height: 964 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto(`${origin}?lang=en`);
    await expect(page.getByRole('heading', { name: 'Quant research for you and your AI Agent' })).toBeVisible();
    await expect(page.locator('.qh-brand img').first()).toHaveAttribute('src', '/brand/qhypo-mark-inverse.svg');
    await expect(page.locator('.qh-header .quantgrove-wordmark')).toHaveText('QAgentis');
    await expect(page.locator('.qh-header .quantgrove-wordmark')).toHaveCSS('font-family', /^Inter(?:,|$)/);
    await expect(page.locator('.qh-header .quantgrove-wordmark')).toHaveCSS('font-weight', '550');
    await expect.poll(() => page.evaluate(() => Array.from(document.fonts).filter(font => font.family === 'Inter').map(font => font.status))).toContain('loaded');
    await expect(page.locator('.qh-language-icon > span').filter({ hasText: /^En$/ })).toHaveCSS('background-color', 'rgb(247, 248, 248)');
    await expect.poll(() => page.locator('.qh-brand img').first().evaluate((image: HTMLImageElement) => image.naturalWidth)).toBeGreaterThan(0);
    await expect(page.getByRole('link', { name: 'Community', exact: true }).first()).toHaveAttribute('href', 'https://discord.gg/tdwxubVhMJ');
    await expect(page.getByRole('link', { name: 'Connect your agent with MCP' })).toHaveAttribute('href', '/login?lang=en&returnTo=%2Fconnections%2Fmcp');
    await expect(page.getByRole('link', { name: 'Get started', exact: true }).first()).toHaveCSS('background-color', 'rgb(94, 106, 210)');
    await page.getByRole('link', { name: 'View example', exact: true }).click();
    await expect(page.getByText('Two factor evaluations completed.', { exact: true })).toBeVisible();
    await expect(page.getByRole('textbox', { name: 'Ask a research question…' })).toBeDisabled();
    const evidence = page.getByRole('tabpanel', { name: 'Factor evidence', exact: true });
    await expect(evidence).toContainText('-rank(pct_change(close, 5))');
    await expect(evidence).toContainText('15 / 21 days');
    await page.getByRole('button', { name: '1 trading day', exact: true }).click();
    await expect(evidence).toContainText('0.082');
    await expect(evidence).toContainText('19 / 21 days');
    await page.getByRole('tab', { name: 'Factor evidence', exact: true }).focus();
    await page.keyboard.press('ArrowRight');
    await expect(page.getByRole('tab', { name: 'Inputs', exact: true })).toBeFocused();
    await expect(page.getByRole('tabpanel', { name: 'Inputs', exact: true })).toContainText('Top 300 stocks');
    await page.keyboard.press('End');
    await expect(page.getByRole('tabpanel', { name: 'Configuration', exact: true })).toContainText('Cross-sectional rank');
    const language = page.getByRole('button', { name: 'Switch to Chinese', exact: true });
    await language.focus();
    await expect(page.getByRole('tooltip')).toHaveText('English / 中文');
    await page.keyboard.press('Escape');
    await expect(page.getByRole('tooltip')).toHaveCount(0);
    await language.click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN');
    await expect(page.locator('.qh-language-icon > span').filter({ hasText: /^中$/ })).toHaveCSS('background-color', 'rgb(247, 248, 248)');
    await expect(page.locator('.qh-language-icon > span').filter({ hasText: /^En$/ })).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
    await expect(page.getByRole('heading', { name: /量化研究，\s*与你的 AI Agent 一起。/ })).toBeVisible();
    await expect(page.getByRole('tab', { name: '配置', exact: true })).toHaveAttribute('aria-selected', 'true');
    await expect(page.getByRole('link', { name: '开始研究', exact: true }).first()).toHaveAttribute('href', '/login?lang=zh');
    await page.getByRole('tab', { name: '因子证据', exact: true }).click();
    await expect(page.getByRole('button', { name: '1 个交易日', exact: true })).toHaveAttribute('aria-pressed', 'true');
    expect(apiRequests).toEqual([]);
    await page.evaluate(() => document.fonts.ready);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath(`landing-zh-${width}.png`), fullPage: true });
    await page.reload();
    await expect(page.getByRole('button', { name: '切换为 English', exact: true })).toBeVisible();
    await page.goto(origin);
    await expect(page.locator('html')).toHaveAttribute('lang', 'zh-CN');
    await page.getByRole('button', { name: '切换为 English', exact: true }).click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath(`landing-en-${width}.png`), fullPage: true });
    await page.getByRole('link', { name: 'Log in', exact: true }).first().click();
    await expect(page.getByRole('heading', { name: 'Welcome to QAgentis' })).toBeVisible();
    await expect(page.getByLabel('Email', { exact: true })).toBeVisible();
    await expect(page.locator('.login-brand .quantgrove-wordmark')).toHaveCSS('font-family', /^Inter(?:,|$)/);
    await expect(page.locator('.login-brand .quantgrove-wordmark')).toHaveCSS('font-weight', '550');
  });
}

import { expect, test } from "@playwright/test";
import { buildProductFixture } from "./build-product-fixture";
let fixture: Awaited<ReturnType<typeof buildProductFixture>>;
test.beforeAll(async () => { fixture = await buildProductFixture(new URL("./fixtures/operator-access.tsx", import.meta.url), "OperatorAccessFixture"); });

test("Operator access retains Session confirmation and keyboard state on desktop", async ({ page }) => {
  const requests: string[] = [];
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.route("http://operator.test/**", route => {
    const path = new URL(route.request().url()).pathname;
    requests.push(path);
    if (path === "/") return route.fulfill({ contentType: "text/html", body: '<div id="root"></div>' });
    if (path.endsWith("/researchers")) return route.fulfill({ json: { items: [{ active: true, created_at: "2026-09-26T00:00:00.000Z", current_session_count: 2, display_label: "Researcher".repeat(20), email: "target@example.test", latest_successful_login_at: null, researcher_id: "00000000-0000-4000-8000-000000000002" }], next_cursor: null } });
    if (path.endsWith("/proofs")) return route.fulfill({ status: 400, json: { code: "OPERATOR_CODE_INVALID" } });
    return route.fulfill({ status: 404 });
  });
  await page.goto("http://operator.test/");
  await page.addStyleTag({ content: fixture.styles });
  await page.addScriptTag({ content: fixture.script });
  const table = page.getByRole("table", { name: "Researchers", exact: true });
  await expect(table.getByRole("row")).toHaveCount(2);
  await expect(page.getByRole("button", {name: "Invite Researcher", exact: true})).toHaveCount(0);
  await expect(page.getByRole("table", {name: "Invitations", exact: true})).toHaveCount(0);
  const details = table.getByRole("button", { name: /^Details ·/ });
  await details.click();
  await expect(table.getByText("00000000-0000-4000-8000-000000000002", { exact: true })).toBeVisible();
  await expect(table.getByText("Effective invitation", {exact: true})).toHaveCount(0);
  await page.screenshot({path: test.info().outputPath("researcher-access-1280.png")});
  await details.click();
  const revoke = page.getByRole("button", { name: /Revoke 2 Login Sessions for/ });
  await revoke.click();
  const confirmation = page.getByRole("alertdialog");
  const code = confirmation.getByLabel("Verification code");
  await expect(code).toBeFocused();
  await expect(confirmation).toContainText("target@example.test");
  await code.fill("123456");
  await page.keyboard.press("Control+Shift+L");
  await expect(confirmation.locator('input[autocomplete="one-time-code"]')).toHaveValue("123456");
  await page.keyboard.press("Control+Shift+L");
  await code.press("Enter");
  await expect(confirmation.getByRole("alert")).toContainText("incorrect or has expired");
  await expect(code).toHaveValue("");
  await confirmation.getByRole("button", {name: "Cancel", exact: true}).click();
  await expect(revoke).toBeFocused();
  expect(requests.some(path => path.includes("invitations"))).toBe(false);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
